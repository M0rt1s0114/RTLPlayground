#!/usr/bin/env python3
"""gen_machine_c.py - generate the per-machine firmware definitions under
machine/ from a YAML board description.

The fork keeps boards/*.yaml as the authoring format.  This tool converts one
YAML file into the three files the upstream build expects:

    machine/<machine_id>.c        the "struct machine machine" definition
    machine/<machine_id>.h        MACHINE_MODEL + MACHINE_CHIPSET
    machine/<machine_id>_init.c   optional machine_custom_init() hook (BANK2)

Usage:
    python3 tools/gen_machine_c.py boards/<machine_id>.yaml <machine_dir>

The generated files are committed, so a plain build does not need Python.
Run "make boards" after editing a YAML file.
"""

import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("Error: PyYAML is required.  Install with: pip install pyyaml")

HEADER = "/* AUTO-GENERATED by tools/gen_machine_c.py from boards/{mid}.yaml\n" \
         " * DO NOT EDIT BY HAND - edit the YAML board file instead.\n" \
         " */\n"

CHIPSETS = {"RTL8372", "RTL8373", "RTL8370"}

# GPIO and LED symbol names are read from the firmware headers so the board
# files and the generator cannot drift apart.
def load_symbols(root: Path):
    pins = root / "rtl837x_pins.h"
    leds = root / "rtl837x_leds.h"
    machine_h = root / "machine.h"
    gpio, ledsyms, high = set(), set(), set()
    if pins.exists():
        gpio = set(re.findall(r"#define\s+(GPIO[A-Z0-9_]+)\s", pins.read_text()))
    if leds.exists():
        ledsyms = set(re.findall(r"#define\s+(LEDS_[A-Z0-9_]+)\s", leds.read_text()))
    if machine_h.exists():
        high = {"LED_27", "LED_28_SYS", "LED_29"}
        high |= set(re.findall(r"#define\s+(LED_[0-9A-Z_]+)\s+[0-9]", machine_h.read_text()))
    return gpio | {"GPIO_NA"}, ledsyms, high


def fmt_int_array(values, per_line=None):
    inner = ", ".join(str(int(v)) for v in values)
    return "{" + inner + "}"


def split_expr(expr):
    return [p.strip() for p in str(expr).split("|") if p.strip()]


def check_expr(expr, symbols, where, mid):
    for part in split_expr(expr):
        if re.fullmatch(r"0[xX][0-9a-fA-F]+|\d+", part):
            continue
        if part in symbols:
            continue
        raise SystemExit(f"{mid}: unknown symbol '{part}' in {where}")


def yaml_bool_int(v):
    return 1 if str(v).strip().lower() in ("1", "true", "yes", "on") else 0


def generate(board, mid, gpio_syms, led_syms, high_syms):
    if not re.fullmatch(r"[A-Za-z0-9_]+", mid):
        raise SystemExit(f"machine_id '{mid}' is not a valid C identifier")
    if board.get("machine_id") and board["machine_id"] != mid:
        raise SystemExit(f"{mid}: machine_id '{board['machine_id']}' does not match file name")

    name = str(board.get("machine_name", "")).strip()
    if not name:
        raise SystemExit(f"{mid}: machine_name is required")
    if len(name) > 29:
        print(f"warning: {mid}: machine_name is {len(name)} chars (max 29)", file=sys.stderr)

    chipset = board.get("machine_chipset")
    if not chipset:
        chipset = "RTL8373" if yaml_bool_int(board.get("isRTL8373", 0)) else "RTL8372"
    if chipset not in CHIPSETS:
        raise SystemExit(f"{mid}: unsupported machine_chipset '{chipset}'")

    nsfp = int(board.get("n_sfp", 0))
    n10g = int(board.get("n_10g", 0))

    arrays = {}
    for key in ("log_to_phys_port", "phys_to_log_port", "is_sfp", "port_led_set"):
        vals = [int(v) for v in (board.get(key) or [0] * 9)]
        if len(vals) != 9:
            raise SystemExit(f"{mid}: {key} must have 9 entries")
        arrays[key] = vals

    sfp = board.get("sfp_ports", []) or []
    if len(sfp) != nsfp:
        raise SystemExit(f"{mid}: n_sfp={nsfp} but {len(sfp)} sfp_ports defined")
    if nsfp > 2:
        raise SystemExit(f"{mid}: at most 2 SFP ports are supported")

    reset = str(board.get("reset_pin", "GPIO_NA")).strip()
    check_expr(reset, gpio_syms, "reset_pin", mid)

    hl = board.get("high_leds", {}) or {}
    mux = str(hl.get("mux", "0")).strip()
    enable = str(hl.get("enable", "0")).strip()
    check_expr(mux, high_syms, "high_leds.mux", mid)
    check_expr(enable, high_syms, "high_leds.enable", mid)

    led_sets = board.get("led_sets", []) or []
    if len(led_sets) > 4:
        raise SystemExit(f"{mid}: at most 4 led_sets rows are supported")
    rows = []
    for row in led_sets:
        vals = [str(v) for v in (row if isinstance(row, list) else [row])]
        if len(vals) > 4:
            raise SystemExit(f"{mid}: at most 4 LED conditions per led_sets row")
        while len(vals) < 4:
            vals.append("0")
        for v in vals:
            check_expr(v, led_syms, "led_sets", mid)
        rows.append(vals)
    while len(rows) < 4:
        rows.append(["0", "0", "0", "0"])

    led_mux_custom = yaml_bool_int(board.get("led_mux_custom", 0))
    led_mux = [int(str(v), 0) for v in (board.get("led_mux", []) or [])]
    if len(led_mux) > 28:
        raise SystemExit(f"{mid}: led_mux has more than 28 entries")
    if led_mux_custom and len(led_mux) < 28:
        led_mux += [0] * (28 - len(led_mux))

    mac_offset = board.get("mac_flash_offset", board.get("mac_offset", 0)) or 0
    mac_offset = int(str(mac_offset), 0)
    flash_sio = yaml_bool_int(board.get("flash_sio", 0))

    custom_init = str(board.get("custom_init", "") or "").rstrip()
    custom_prefix = str(board.get("custom_init_prefix", "") or "").rstrip()
    custom_init = "" if custom_init.strip() in ("", "/* nothing */") else custom_init

    c = [HEADER.format(mid=mid), '#include "machine_defs.h"\n\n',
         "__code const struct machine machine = {\n",
         "\tMACHINE_COMMON_SETTING,\n"]
    if mac_offset:
        c.append(f"\t.mac_flash_offset = 0x{mac_offset:06X},\n")
    c.append(f"\t.n_sfp = {nsfp},\n")
    if n10g:
        c.append(f"\t.n_10g = {n10g},\n")
    c.append(f"\t.log_to_phys_port = {fmt_int_array(arrays['log_to_phys_port'])},\n")
    c.append(f"\t.phys_to_log_port = {fmt_int_array(arrays['phys_to_log_port'])},\n")
    c.append(f"\t.is_sfp = {fmt_int_array(arrays['is_sfp'])},\n")
    for idx, s in enumerate(sfp):
        s = s or {}
        for field in ("pin_detect", "pin_los", "pin_tx_disable"):
            val = str(s.get(field, "GPIO_NA")).strip()
            check_expr(val, gpio_syms, f"sfp_port[{idx}].{field}", mid)
            c.append(f"\t.sfp_port[{idx}].{field} = {val},\n")
        c.append(f"\t.sfp_port[{idx}].sds = {int(s.get('sds', 0))},\n")
        bus = s.get("i2c") or {}
        sda = str(bus.get("sda", "GPIO_NA")).strip()
        scl = str(bus.get("scl", "GPIO_NA")).strip()
        check_expr(sda, gpio_syms, f"sfp_port[{idx}].i2c.sda", mid)
        check_expr(scl, gpio_syms, f"sfp_port[{idx}].i2c.scl", mid)
        if sda != "GPIO_NA" and scl != "GPIO_NA":
            c.append(f"\t.sfp_port[{idx}].i2c = I2CBUS( {sda}, {scl} ),\n")
    c.append(f"\t.reset_pin = {reset},\n")
    c.append(f"\t.high_leds = {{ .mux = {mux}, .enable = {enable} }},\n")
    c.append(f"\t.port_led_set = {fmt_int_array(arrays['port_led_set'])},\n")
    c.append("\t.led_sets = {\n")
    for row in rows:
        c.append("\t\t{ " + ", ".join(row) + " },\n")
    c.append("\t},\n")
    if led_mux_custom:
        c.append("\t.led_mux_custom = 1,\n")
        c.append("\t.led_mux = {" + ", ".join(f"0x{v:02x}" for v in led_mux) + "},\n")
    if flash_sio:
        c.append("\t.flash_sio = 1,\n")
    c.append("};\n")

    h = [HEADER.format(mid=mid),
         f"#ifndef _MACHINE_{mid.upper()}_H_\n",
         f"#define _MACHINE_{mid.upper()}_H_\n\n",
         f'#define MACHINE_MODEL "{name}"\n',
         f"#define MACHINE_CHIPSET {chipset}\n"]
    if board.get("min_port") is not None:
        h.append(f"#define MACHINE_MIN_PORT {int(board['min_port'])}\n")
    if board.get("max_port") is not None:
        h.append(f"#define MACHINE_MAX_PORT {int(board['max_port'])}\n")
    h.append(f"\n#endif\n")

    init = None
    if custom_init or custom_prefix:
        init = [HEADER.format(mid=mid), '#include "machine_init_defs.h"\n\n']
        if custom_prefix:
            init.append(custom_prefix + "\n\n")
        init.append("void machine_custom_init(void) __banked\n{\n")
        if custom_init:
            for line in custom_init.splitlines():
                init.append(("\t" + line if line.strip() else "") + "\n")
        init.append("}\n")
    return "".join(c), "".join(h), ("".join(init) if init else None)


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: gen_machine_c.py boards/<machine_id>.yaml <machine_dir>")
    yaml_path = Path(sys.argv[1])
    outdir = Path(sys.argv[2])
    mid = yaml_path.stem
    board = yaml.safe_load(yaml_path.read_text(encoding="utf-8")) or {}
    root = Path.cwd()
    gpio_syms, led_syms, high_syms = load_symbols(root)
    c_text, h_text, init_text = generate(board, mid, gpio_syms, led_syms, high_syms)
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / (mid + ".c")).write_text(c_text, encoding="utf-8", newline="\n")
    (outdir / (mid + ".h")).write_text(h_text, encoding="utf-8", newline="\n")
    init_path = outdir / (mid + "_init.c")
    if init_text is not None:
        init_path.write_text(init_text, encoding="utf-8", newline="\n")
    elif init_path.exists():
        init_path.unlink()
        print("removed stale", init_path)


if __name__ == "__main__":
    main()
